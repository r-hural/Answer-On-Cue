/** "Question 3" or "Questions 1–3", from zero-based indexes in order. */
function rangeOf(indexes: number[]): string {
  const first = indexes[0] + 1
  const last = indexes[indexes.length - 1] + 1
  return first === last ? `Question ${first}` : `Questions ${first}\u2013${last}`
}

/** "1, 2 and 3". */
function listOf(numbers: number[]): string {
  return numbers.length < 2 ? numbers.join('') : `${numbers.slice(0, -1).join(', ')} and ${numbers[numbers.length - 1]}`
}
